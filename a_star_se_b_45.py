from queue import PriorityQueue

def a_star_search(graph, start, goal, h):
  open_set = PriorityQueue()
  open_set.put((0, start)) # Corrected: (priority, item). Initial cost to start is 0.
  g_score = {node: float('inf') for node in graph.keys()} # Changed graph.nodes() to graph.keys()
  g_score[start] = 0  # Cost to reach start is zero
  came_from = {}

  while not open_set.empty():
    current_priority, current = open_set.get()

    if current == goal:
      path = []
      while current in came_from:
        path.append(current)
        current = came_from[current]
      path.append(start)
      path.reverse()
      return path, g_score[goal]

    for neighbor, cost in graph[current]: # graph is now directly the dictionary
      new_cost = g_score[current] + cost
      if new_cost < g_score[neighbor]:
        g_score[neighbor] = new_cost
        priority = new_cost + h(neighbor)
        open_set.put((priority, neighbor))
        came_from[neighbor] = current

  return None, float('inf') # Goal not reachable

# Graph definition
graph = {
    'A': [('B', 1), ('C', 4)],
    'B': [('A', 1), ('C', 2), ('D', 5)],
    'C': [('A', 4), ('B', 2), ('D', 1)],
    'D': [('B', 5), ('C', 1)]
}

# Heuristics definition
heuristics = {
    'A': 7,
    'B': 6,
    'C': 2,
    'D': 0
}

def h(node):
  return heuristics.get(node, float('inf'))

# Removed GraphWrapper class as it's no longer needed.

# Call a_star_search with the dictionary directly
path, cost = a_star_search(graph, 'A', 'D', h)
print("Path:", path)
print("Cost:", cost)